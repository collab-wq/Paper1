function run_paderborn_batch
% Three official accelerated-life/healthy records at one operating point.
ids={'K001','KA04','KI04'};
outdir=fullfile('results','paderborn');
if ~exist(outdir,'dir'), mkdir(outdir); end
fid=fopen(fullfile(outdir,'pilot_summary.csv'),'w');
assert(fid>0);
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,['bearing,record,start_sample,rpm,force_N,torque_Nm,' ...
    'bpfo_hz,bpfi_hz,raw_bpfo_peak_hz,fused_bpfo_peak_hz,' ...
    'raw_bpfo_contrast,fused_bpfo_contrast,raw_bpfi_peak_hz,' ...
    'fused_bpfi_peak_hz,raw_bpfi_contrast,fused_bpfi_contrast,' ...
    'retained_fraction,eligible_pairs\n']);
for k=1:numel(ids)
    id=ids{k}; rec=1; startIndex=64001;
    file=fullfile('input','paderborn',id, ...
        sprintf('N15_M07_F10_%s_%d.mat',id,rec));
    r=main_Paper1('paderborn',file,startIndex);
    fprintf(fid,['%s,%d,%d,%.6f,%.6f,%.6f,%.6f,%.6f,' ...
        '%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.8f,%d\n'], ...
        id,rec,startIndex,r.rpm,r.measured_force_N,r.measured_torque_Nm, ...
        r.bpfo_hz,r.bpfi_hz,r.raw_bpfo_peak_hz,r.fused_bpfo_peak_hz, ...
        r.raw_bpfo_contrast,r.fused_bpfo_contrast, ...
        r.raw_bpfi_peak_hz,r.fused_bpfi_peak_hz, ...
        r.raw_bpfi_contrast,r.fused_bpfi_contrast, ...
        r.retained_pixel_fraction,r.eligible_time_pairs);
end
end
