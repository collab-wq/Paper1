function write_adaptive_candidate_csv(file,summary)
% Export every evaluated (R,h) pair, including invalid candidates.
items=summary.candidates;
fid=fopen(file,'w'); assert(fid>0,'Cannot open candidate CSV');
guard=onCleanup(@() fclose(fid));
fprintf(fid,['R,hypothesis,theoretical_hz,target_peak_hz,error_hz,' ...
    'contrast_linear,location_confidence,contrast_utility,J,valid,' ...
    'reason,available_band_count,band_centers_hz,band_bounds_hz,' ...
    'valid_band_pair_windows,frequency_triplet_count,' ...
    'time_endpoint_count,time_pair_count,raw_target_peak_hz,' ...
    'raw_target_contrast,unlabelled_raw_peak_hz,' ...
    'unlabelled_fused_peak_hz,retained_pixel_fraction\n']);
for k=1:numel(items)
    c=items(k); b=c.bands_hz;
    if isempty(b), centers=''; bounds='';
    else
        centers=strjoin(compose('%.6g',mean(b,2)),';');
        bounds=strjoin(compose('%.6g:%.6g',b(:,1),b(:,2)),';');
    end
    fprintf(fid,'%d,%s,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%d,%s,%.12g,%s,%s,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g\n', ...
        c.R,quote(c.hypothesis),c.theoretical_hz,c.target_peak_hz, ...
        c.error_hz,c.contrast_linear,c.location_confidence, ...
        c.contrast_utility,c.J,c.valid,quote(c.reason), ...
        c.available_band_count,quote(centers),quote(bounds), ...
        c.valid_band_pair_windows,c.frequency_triplet_count, ...
        c.time_endpoint_count,c.time_pair_count,c.raw_target_peak_hz, ...
        c.raw_target_contrast,c.unlabelled_raw_peak_hz, ...
        c.unlabelled_fused_peak_hz,c.retained_pixel_fraction);
end
end

function s=quote(value)
s=['"' strrep(char(value),'"','""') '"'];
end
