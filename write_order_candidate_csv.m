function write_order_candidate_csv(path,summary)
rows=summary.candidates;
fid=fopen(path,'w'); assert(fid>0);
closer=onCleanup(@() fclose(fid));
fprintf(fid,['target_fault_type,target_hypothesis,selected_R,selected,R,hypothesis,theoretical_order,target_peak_order,error_order,' ...
    'physical_resolution_order,contrast_linear,location_confidence,' ...
    'contrast_utility,J,valid,reason,band_bounds_hz,' ...
    'frequency_triplet_count,time_endpoint_count,time_pair_count\n']);
for k=1:numel(rows)
    r=rows(k);
    bounds=jsonencode(r.bands_hz);
    chosen=strcmp(summary.status,'SELECTED') && ...
        k==summary.selected_candidate_index;
    selectedR=NaN;
    if strcmp(summary.status,'SELECTED'), selectedR=summary.selected_R; end
    fprintf(fid,'%s,%s,%.12g,%d,%d,%s,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%d,%s,%s,%.12g,%.12g,%.12g\n', ...
        summary.target_fault_type,summary.target_hypothesis,selectedR,chosen, ...
        r.R,r.hypothesis,r.theoretical_order,r.target_peak_order, ...
        r.error_order,r.physical_resolution_order,r.contrast_linear, ...
        r.location_confidence,r.contrast_utility,r.J,r.valid, ...
        r.reason,['"' strrep(bounds,'"','""') '"'], ...
        r.frequency_triplet_count,r.time_endpoint_count,r.time_pair_count);
end
end
